//! # クリップボードへのコピーと自動消去 (`sys::clipboard`)
//!
//! 秘密をクリップボードへコピーし、一定時間の後に消去する処理を置く。現時点では未実装である。
//!
//! ## 担う処理
//!
//! - 機密フィールド (パスワード、TOTP など) のコピー時に、クリップボード履歴からの除外を指定する
//! - コピーから 30 秒後に、内容が変わっていなければ消去する
//!
//! ## OS ごとの差
//!
//! | 処理 | Linux (X11 / Wayland) | macOS | Windows (未対応) |
//! | :-- | :-- | :-- | :-- |
//! | 内容の保持 | コピー元のプロセスが保持する。消去までプロセスを残す必要がある | ペーストボードのサーバーが保持する | OS が保持する |
//! | 履歴からの除外 | `x-kde-passwordManagerHint` | `org.nspasteboard.ConcealedType` | 履歴とクラウド同期を除外するフォーマット |
//!
//! ## Notes
//!
//! 履歴の除外指定を見ずに内容を記録するクリップボードマネージャーには、どの OS でも防御できない。
