//! # 端末からの秘密の入力 (`sys::tty`)
//!
//! マスターパスワードなどの秘密を、エコーさせずに読み込む処理を置く。現時点では未実装である。
//!
//! ## 担う処理
//!
//! - 標準入力ではなく制御端末を開き、エコーを止めて固定容量のバッファへ読み込む
//! - `SIGINT` / `SIGTERM` を受けたときに、端末属性を元に戻し、読み込み途中の秘密を消去する
//! - 非対話の入力のうち、ファイルディスクリプターの番号で指定された入力元を開く
//!
//! ## OS ごとの差
//!
//! | 処理 | POSIX | Windows (未対応) |
//! | :-- | :-- | :-- |
//! | 制御端末 | `/dev/tty` | `CONIN$` |
//! | エコーの停止と復元 | `termios` の `ECHO` を `tcsetattr` で切り替える | `SetConsoleMode` で `ENABLE_ECHO_INPUT` を外す |
//! | 中断の捕捉 | `SIGINT` / `SIGTERM` のシグナルハンドラー | `SetConsoleCtrlHandler` |
